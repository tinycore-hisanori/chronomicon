_hw_sprite = st.builds(
    HWSprite,
    x_offset=st.integers(-128, 127),
    y_offset=st.integers(-128, 127),
    oam_tile=st.integers(0, 255),
    attributes=st.integers(0, 255),
)
_metasprites = st.lists(
    st.builds(
        MetaspriteEntry,
        name=st.sampled_from(["hero", "enemy", "coin"]),
        width=st.sampled_from([8, 16]),
        hw_sprites=st.lists(_hw_sprite, max_size=3).map(tuple),
        is_flip=st.booleans(),
    ),
    max_size=3,
).map(lambda entries: MetaspriteTable(entries=tuple(entries)))


@st.composite
def _results(draw) -> ConversionResult:
    n = draw(st.integers(0, 2))
    nametables = tuple(
        NametableData(screen_index=i, tile_ids=tuple(draw(st.lists(
            st.integers(0, 255), min_size=960, max_size=960))))
        for i in range(n)
    )
    attrs = tuple(
        AttributeTable(screen_index=i, data=draw(st.binary(min_size=64, max_size=64)))
        for i in range(n)
    )
    return ConversionResult(
        chr_bin=draw(st.binary(max_size=CHR_SIZE)),
        palette_set=draw(_palette_set),
        nametables=nametables,
        attr_tables=attrs,
        metasprites=draw(_metasprites),
    )


# Feature: asset-converter, Property 6: chr.bin is always 8192 bytes
# **Validates: Requirements 9.1, 9.4**
@given(result=_results())
def test_chr_bin_always_8192_bytes(result: ConversionResult) -> None:
    with tempfile.TemporaryDirectory() as tmp:
        out = emit_all(result, Path(tmp) / "out")
        data = (Path(tmp) / "out" / "chr.bin").read_bytes()

    n = len(result.chr_bin)
    assert len(data) == CHR_SIZE == 8192
    assert data[:n] == result.chr_bin
    assert data[n:] == bytes(CHR_SIZE - n)
    assert out.byte_lengths["chr.bin"] == 8192
    assert out.checksums["chr.bin"] == f"{zlib.crc32(data) & 0xFFFFFFFF:08x}"


