def _small_result(screens=(), sprite_names=(), n_screens: int = 1) -> ConversionResult:
    palette_set = PaletteSet(
        bg=(PaletteDef("bg0", (1, 2)),),
        sprite=(PaletteDef("sp0", (3, 4, 5)),),
        nes_colors={1: 0x11, 2: 0x21, 3: 0x16, 4: 0x27, 5: 0x30},
    )
    metasprites = MetaspriteTable(
        entries=(
            MetaspriteEntry(
                "hero", 16,
                (HWSprite(0, 0, 0x01, 0x00), HWSprite(-8, 16, 0x03, 0x01)),
                False,
            ),
            MetaspriteEntry(
                "hero", 16,
                (HWSprite(8, 0, 0x01, 0x40), HWSprite(16, 16, 0x03, 0x41)),
                True,
            ),
        )
    )
    return ConversionResult(
        chr_bin=b"\x01\x02",
        palette_set=palette_set,
        nametables=tuple(
            NametableData(i, tuple((j + i) % 256 for j in range(960))) for i in range(n_screens)
        ),
        attr_tables=tuple(
            AttributeTable(i, bytes((j + i) % 256 for j in range(64))) for i in range(n_screens)
        ),
        metasprites=metasprites,
        screens=tuple(screens),
        sprite_names=tuple(sprite_names),
    )


