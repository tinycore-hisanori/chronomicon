def test_assets_h_pads_missing_palettes_and_colors() -> None:
    ps = PaletteSet(bg=(), sprite=(), nes_colors={})
    result = ConversionResult(
        chr_bin=b"", palette_set=ps, nametables=(), attr_tables=(),
        metasprites=MetaspriteTable(entries=()),
    )
    text = build_assets_h(result)
    assert text.count("0x0f") == 32  # BG and sprite palettes entirely padded with 0x0f
    # unmapped Pyxel color falls back to the padding value
    ps2 = PaletteSet(bg=(PaletteDef("a", (1, 9)),), sprite=(), nes_colors={1: 0x11})
    text2 = build_assets_h(ConversionResult(
        chr_bin=b"", palette_set=ps2, nametables=(), attr_tables=(),
        metasprites=MetaspriteTable(entries=()),
    ))
    assert "    0x11,0x11,0x11,0x11,  0x11,0x11,0x11,0x11,\n" in text2


def test_nametable_snapshot_no_objects() -> None:
    result = _small_result()
    text = build_nametable_s(result, 0)
    nt = [f"    .byte {','.join(f'${(r * 32 + c) % 256:02x}' for c in range(32))}"
          for r in range(30)]
    at = [f"    .byte {','.join(f'${r * 8 + c:02x}' for c in range(8))}" for r in range(8)]
    expected = "\n".join(
        [
            "; Generated by Chronomicon. Screen 0.",
            '.segment "RODATA"',
            ".export _screen0_nametable, _screen0_attr, _screen0_objects",
            "",
            "_screen0_nametable:        ; 960 bytes, 30 rows x 32 columns",
            *nt,
            "",
            "_screen0_attr:             ; 64 bytes",
            *at,
            "",
            "_screen0_objects:          ; x, y (display Y), metasprite index; ends with $ff",
            "    .byte $ff",
        ]
    ) + "\n"
    assert text == expected


def _screen(count: int, objects=()) -> ScreenDef:
    return ScreenDef(0, 0, 0, count, 0, 0, 0, tuple(objects))


def _objects_block(text: str) -> list[str]:
    lines = text.splitlines()
    i = next(k for k, ln in enumerate(lines) if ln.startswith("_screen") and "_objects:" in ln)
    return lines[i + 1:]


def test_objects_table_split_by_screen_and_order() -> None:
    objs = (
        ObjectDef("coin", 10, 20, 1),
        ObjectDef("hero", 30, 0, 0),
        ObjectDef("coin", 40, 50, 1),
    )
    result = _small_result(
        screens=[_screen(2, objs)], sprite_names=("hero", "coin"), n_screens=2
    )
    assert _objects_block(build_nametable_s(result, 0)) == ["    .byte 30, 0, 0", "    .byte $ff"]
    assert _objects_block(build_nametable_s(result, 1)) == [
        "    .byte 10, 20, 1",
        "    .byte 40, 50, 1",
        "    .byte $ff",
    ]


def test_objects_table_second_entry_uses_global_index() -> None:
    result = _small_result(
        screens=[_screen(1), _screen(1, (ObjectDef("coin", 5, 7, 0),))],
        sprite_names=("hero", "coin"),
        n_screens=2,
    )
    assert _objects_block(build_nametable_s(result, 0)) == ["    .byte $ff"]
    assert _objects_block(build_nametable_s(result, 1)) == ["    .byte 5, 7, 1", "    .byte $ff"]


def test_objects_y_is_written_as_given() -> None:
    result = _small_result(
        screens=[_screen(1, (ObjectDef("hero", 0, 0, 0), ObjectDef("hero", 255, 255, 0)))],
        sprite_names=("hero",),
    )
    assert _objects_block(build_nametable_s(result, 0)) == [
        "    .byte 0, 0, 0",
        "    .byte 255, 255, 0",
        "    .byte $ff",
    ]


def test_emit_creates_missing_out_dir_and_parent(tmp_path: Path) -> None:
    out = tmp_path / "a" / "b" / "out"
    res = emit_all(_small_result(), out)
    assert set(res.files) == {"chr.bin", "assets.h", "nametable_0.s"}
    for p in res.files.values():
        assert p.parent == out and p.is_file()
    assert [p.name for p in (tmp_path / "a" / "b").iterdir()] == ["out"]
    assert not list(tmp_path.rglob(".chrono-*"))


def test_emit_failure_keeps_previous_files_and_removes_temp(
    tmp_path: Path, monkeypatch: pytest.MonkeyPatch
) -> None:
    out = tmp_path / "out"
    emit_all(_small_result(n_screens=2), out)
    before = {p.name: p.read_bytes() for p in out.iterdir()}

    real_write = Path.write_bytes

    def failing(self: Path, data: bytes) -> int:
        if self.name == "nametable_1.s":
            raise OSError("disk full")
        return real_write(self, data)

    monkeypatch.setattr(Path, "write_bytes", failing)
    changed = _small_result(n_screens=2)
    changed = ConversionResult(
        chr_bin=b"\xff" * 16, palette_set=changed.palette_set,
        nametables=changed.nametables, attr_tables=changed.attr_tables,
        metasprites=changed.metasprites,
    )
    with pytest.raises(OSError):
        emit_all(changed, out)
    monkeypatch.undo()

    assert {p.name: p.read_bytes() for p in out.iterdir()} == before
    assert not list(tmp_path.glob(".chrono-*"))
