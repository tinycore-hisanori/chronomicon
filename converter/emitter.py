"""Emitter: write chr.bin, assets.h and nametable_N.s atomically into an output directory."""

from __future__ import annotations

import os
import shutil
import tempfile
import zlib
from pathlib import Path

from converter.models import (
    ConversionResult,
    EmitResult,
    MetaspriteEntry,
    PaletteDef,
    PaletteSet,
)

CHR_SIZE = 8192
DEFAULT_SPRITE_COLOR = 0x0F  # NES black, used for missing sprite palette colors
DEFAULT_BG_COLOR = 0x0F  # used for BG padding when no BG palette is defined


def _common_bg_color(palette_set: PaletteSet) -> int:
    """Universal background color: first color of the first BG palette (NES byte)."""
    if palette_set.bg and palette_set.bg[0].pyxel_colors:
        return palette_set.nes_colors.get(palette_set.bg[0].pyxel_colors[0], DEFAULT_BG_COLOR)
    return DEFAULT_BG_COLOR


def _palette_bytes(
    palettes: tuple[PaletteDef, ...], nes_colors: dict[int, int], pad: int
) -> list[int]:
    """16 NES bytes (4 palettes x 4 colors); missing palettes/colors are filled with `pad`."""
    out: list[int] = []
    for i in range(4):
        colors = list(palettes[i].pyxel_colors) if i < len(palettes) else []
        row = [nes_colors.get(c, pad) for c in colors[:4]]
        row += [pad] * (4 - len(row))
        out.extend(row)
    return out


def _fmt_palette(name: str, values: list[int]) -> str:
    rows = [",".join(f"0x{v:02x}" for v in values[i : i + 4]) for i in range(0, 16, 4)]
    body = f"    {rows[0]},  {rows[1]},\n    {rows[2]},  {rows[3]}"
    return f"const unsigned char {name}[16] = {{\n{body}\n}};\n"


def _signed(v: int) -> str:
    v = int(v)
    return str(v) if v >= 0 else f"(unsigned char){v}"


def _metasprite_text(entry: MetaspriteEntry) -> str:
    suffix = "_flip" if entry.is_flip else ""
    lines = [f"const unsigned char metasprite_{entry.name}{suffix}[] = {{"]
    for hw in entry.hw_sprites:
        lines.append(
            f"    {_signed(hw.x_offset)}, {_signed(hw.y_offset)}, "
            f"0x{hw.oam_tile:02x}, 0x{hw.attributes:02x},"
        )
    lines.append("    128")
    lines.append("};")
    return "\n".join(lines) + "\n"


def build_assets_h(result: ConversionResult) -> str:
    """assets.h text. BG padding = common background color, sprite padding = 0x0F."""
    ps = result.palette_set
    bg = _palette_bytes(ps.bg, ps.nes_colors, _common_bg_color(ps))
    spr = _palette_bytes(ps.sprite, ps.nes_colors, DEFAULT_SPRITE_COLOR)
    parts = [
        "/* Generated by Chronomicon. Do not edit. */\n#ifndef ASSETS_H\n#define ASSETS_H\n\n",
        _fmt_palette("palette_bg", bg),
        _fmt_palette("palette_sprite", spr),
    ]
    for entry in result.metasprites.entries:
        parts.append("\n" + _metasprite_text(entry))
    parts.append("\n#endif\n")
    return "".join(parts)


def _byte_lines(values, per_line: int, indent: str = "    ") -> list[str]:
    return [
        indent + ".byte " + ",".join(f"${v:02x}" for v in values[i : i + per_line])
        for i in range(0, len(values), per_line)
    ]


def _objects_for_screen(result: ConversionResult, screen_index: int) -> list[tuple[int, int, int]]:
    """Objects of global screen `screen_index` (entries cover consecutive indices)."""
    base = 0
    for entry in result.screens:
        if base <= screen_index < base + entry.count:
            local = screen_index - base
            out = []
            for obj in entry.objects:
                if obj.screen == local:
                    out.append((obj.x, obj.y, result.sprite_names.index(obj.name)))
            return out
        base += entry.count
    return []


def build_nametable_s(result: ConversionResult, pos: int) -> str:
    nt = result.nametables[pos]
    at = result.attr_tables[pos]
    n = nt.screen_index
    lines = [
        f"; Generated by Chronomicon. Screen {n}.",
        '.segment "RODATA"',
        f".export _screen{n}_nametable, _screen{n}_attr, _screen{n}_objects",
        "",
        f"_screen{n}_nametable:        ; 960 bytes, 30 rows x 32 columns",
        *_byte_lines(nt.tile_ids, 32),
        "",
        f"_screen{n}_attr:             ; 64 bytes",
        *_byte_lines(list(at.data), 8),
        "",
        f"_screen{n}_objects:          ; x, y (display Y), metasprite index; ends with $ff",
    ]
    for x, y, idx in _objects_for_screen(result, n):
        lines.append(f"    .byte {x}, {y}, {idx}")
    lines.append("    .byte $ff")
    return "\n".join(lines) + "\n"


def _chr_bytes(result: ConversionResult) -> bytes:
    data = bytes(result.chr_bin[:CHR_SIZE])
    return data + bytes(CHR_SIZE - len(data))


def emit_all(result: ConversionResult, out_dir: Path) -> EmitResult:
    """Write all files to a temporary directory, then move them into out_dir."""
    out_dir = Path(out_dir)
    contents: dict[str, bytes] = {
        "chr.bin": _chr_bytes(result),
        "assets.h": build_assets_h(result).encode("utf-8"),
    }
    for pos, nt in enumerate(result.nametables):
        contents[f"nametable_{nt.screen_index}.s"] = build_nametable_s(result, pos).encode("utf-8")

    tmp_dir: Path | None = None
    same_fs = True
    try:
        try:
            parent = out_dir.parent
            parent.mkdir(parents=True, exist_ok=True) if not parent.exists() else None
            tmp_dir = Path(tempfile.mkdtemp(prefix=".chrono-", dir=parent))
        except OSError:
            tmp_dir = Path(tempfile.mkdtemp(prefix=".chrono-"))
            same_fs = False

        checksums: dict[str, str] = {}
        lengths: dict[str, int] = {}
        for name, data in contents.items():
            (tmp_dir / name).write_bytes(data)
            checksums[name] = f"{zlib.crc32(data) & 0xFFFFFFFF:08x}"
            lengths[name] = len(data)

        out_dir.mkdir(parents=True, exist_ok=True)
        files: dict[str, Path] = {}
        for name in contents:
            dest = out_dir / name
            if same_fs:
                os.replace(tmp_dir / name, dest)
            else:
                shutil.move(str(tmp_dir / name), str(dest))
            files[name] = dest
        return EmitResult(files=files, checksums=checksums, byte_lengths=lengths)
    finally:
        if tmp_dir is not None:
            shutil.rmtree(tmp_dir, ignore_errors=True)
