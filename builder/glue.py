"""Generated glue files between the Converter output and the Runtime.

Writes three files next to the Converter output:

* ``assets_data.c``: the only translation unit that includes ``assets.h``
  (which *defines* its arrays).
* ``assets_decl.h``: ``extern`` declarations for every array defined in ``assets.h``.
* ``screens.s``: ca65 lookup tables (``screen_nt_lo`` and friends) over all screens.
"""

from __future__ import annotations

import re
from dataclasses import dataclass
from pathlib import Path

from builder.errors import BuildError

MAX_SCREENS = 255

_DEFINITION_RE = re.compile(r"^const unsigned char (\w+)\[\d*\]\s*=", re.MULTILINE)
_NAMETABLE_FILE_RE = re.compile(r"^nametable_(\d+)\.s$")


@dataclass(frozen=True)
class GlueInfo:
    """Result of `write_glue`."""

    screen_count: int
    extern_names: tuple[str, ...]


def _find_screen_numbers(assets_dir: Path) -> list[int]:
    numbers = []
    for path in assets_dir.iterdir():
        match = _NAMETABLE_FILE_RE.match(path.name)
        if match and path.is_file():
            numbers.append(int(match.group(1)))
    return sorted(numbers)


def _check_numbering(numbers: list[int]) -> None:
    if not numbers:
        raise BuildError("no screens: the converter produced no nametable_N.s files")
    if numbers != list(range(len(numbers))):
        missing = sorted(set(range(numbers[-1] + 1)) - set(numbers))
        detail = f"missing nametable_{missing[0]}.s" if missing else "duplicate screen numbers"
        raise BuildError(
            f"nametable_N.s numbering must be 0..{len(numbers) - 1} without gaps: {detail}"
        )
    if len(numbers) > MAX_SCREENS:
        raise BuildError(f"too many screens: {len(numbers)} (maximum is {MAX_SCREENS})")


def _assets_data_c() -> str:
    return (
        "/* Generated by Chronomicon. Do not edit.\n"
        " * The only translation unit that includes assets.h (it defines its arrays). */\n"
        '#include "assets.h"\n'
    )


def _assets_decl_h(names: list[str]) -> str:
    lines = [
        "/* Generated by Chronomicon. Do not edit. */",
        "#ifndef ASSETS_DECL_H",
        "#define ASSETS_DECL_H",
        "",
    ]
    lines += [f"extern const unsigned char {name}[];" for name in names]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def _byte_table(label: str, exprs: list[str]) -> list[str]:
    lines = [f"{label}:"]
    for i in range(0, len(exprs), 8):
        lines.append("    .byte " + ", ".join(exprs[i : i + 8]))
    return lines


def _screens_s(count: int) -> str:
    symbols = [f"_screen{i}_{kind}" for i in range(count) for kind in ("nametable", "attr")]
    nt = [f"_screen{i}_nametable" for i in range(count)]
    at = [f"_screen{i}_attr" for i in range(count)]
    lines = [
        "; Generated by Chronomicon. Do not edit.",
        f".import {', '.join(symbols)}",
        ".export _screen_count, screen_nt_lo, screen_nt_hi, screen_at_lo, screen_at_hi",
        "",
        '.segment "RODATA"',
        "",
        f"_screen_count:  .byte {count}",
        "",
        *_byte_table("screen_nt_lo", [f"<{s}" for s in nt]),
        *_byte_table("screen_nt_hi", [f">{s}" for s in nt]),
        *_byte_table("screen_at_lo", [f"<{s}" for s in at]),
        *_byte_table("screen_at_hi", [f">{s}" for s in at]),
        "",
    ]
    return "\n".join(lines)


def _write_text(path: Path, text: str) -> None:
    # newline="" keeps "\n" line endings on every platform (deterministic output).
    with open(path, "w", encoding="utf-8", newline="") as handle:
        handle.write(text)


def write_glue(assets_dir: Path | str) -> GlueInfo:
    """Write assets_data.c, assets_decl.h and screens.s into `assets_dir`."""
    assets_dir = Path(assets_dir)
    try:
        numbers = _find_screen_numbers(assets_dir)
        _check_numbering(numbers)
        assets_h = (assets_dir / "assets.h").read_text(encoding="utf-8")
        names = _DEFINITION_RE.findall(assets_h)
        count = len(numbers)
        _write_text(assets_dir / "assets_data.c", _assets_data_c())
        _write_text(assets_dir / "assets_decl.h", _assets_decl_h(names))
        _write_text(assets_dir / "screens.s", _screens_s(count))
    except OSError as exc:
        raise BuildError(f"cannot write glue files in {assets_dir}: {exc}") from exc
    return GlueInfo(screen_count=count, extern_names=tuple(names))
